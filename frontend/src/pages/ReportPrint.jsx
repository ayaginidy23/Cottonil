// =============================================================================
// ReportPrint.jsx - A Report Agent report as a bilingual document (EN + AR)
//   /print/report/<id>  -> "Save as PDF" = the browser's print-to-PDF
// =============================================================================
import { useEffect, useState } from 'react'
import { useParams } from 'react-router-dom'
import { Printer } from 'lucide-react'
import ReportView from '../components/ReportView.jsx'
import { api } from '../lib/api.js'

export default function ReportPrint() {
  const { reportId } = useParams()
  const [report, setReport] = useState(null)
  const [error, setError] = useState(null)

  useEffect(() => {
    api.report(reportId).then(setReport).catch((e) => setError(e.message))
  }, [reportId])

  if (error) return <div className="doc"><div className="error-box">{error}</div></div>
  if (!report) return <div className="doc muted">Loading… · جاري التحميل</div>

  return (
    <div className="doc doc-report">
      <div className="doc-toolbar no-print">
        <button className="action-btn primary" onClick={() => window.print()}>
          <Printer size={16} /> Save as PDF · حفظ PDF
        </button>
        <span className="muted small">In the print window choose "Save as PDF" · اختار Save as PDF</span>
      </div>
      <header className="doc-header">
        <img src="/cottonil-logo-blue.png" alt="Cottonil" className="doc-logo"
          onError={(e) => { e.currentTarget.style.display = 'none' }} />
        <div className="doc-sub">
          <div>Management report · تقرير إداري</div>
          <div>{report.created_at} · Topic / الموضوع: <span dir="auto">{report.topic}</span></div>
        </div>
      </header>
      <ReportView report={report} lang="both" />
      <p className="muted small doc-foot">
        Generated by the Cottonil Report Agent from the gold data layer (read-only queries).
        <br />
        <span dir="rtl" lang="ar">التقرير ده اتعمل بواسطة وكيل التقارير من طبقة gold (استعلامات قراءة بس).</span>
      </p>
    </div>
  )
}
